"""Embed package/config.ini in the DLL (build/config_template_embed.h), so the mod can add option lines a kept config.ini lacks.

usage: python -I tools/config_embed.py <project root>
"""
import sys
from pathlib import Path


def c_literal(data: bytes) -> str:
    """Return the bytes as C string-literal lines (one source line per config line)."""
    out = []
    for line in data.split(b"\n"):
        text = line.decode("ascii")
        esc = text.replace("\\", "\\\\").replace("\"", "\\\"").replace("\r", "\\r").replace("\t", "\\t")
        out.append("    \"" + esc + "\\n\"")
    if data.endswith(b"\n"):
        out.pop()  # the split's empty tail: its newline is already on the line before
    else:
        out[-1] = out[-1][:-3] + "\""  # no newline after the last line
    return "\n".join(out)


def main() -> int:
    """Write build/config_template_embed.h from package/config.ini (ASCII only, no [Debug])."""
    root = Path(sys.argv[1])
    data = (root / "package" / "config.ini").read_bytes()
    data.decode("ascii")  # refuses anything but ASCII
    assert b"[Debug]" not in data, "package/config.ini carries debug settings"
    head = ("// Generated by tools/config_embed.py from package/config.ini: do not edit.\n"
            "#pragma once\n"
            "static const char kConfigTemplate[] =\n")
    text = head + c_literal(data) + ";\n"
    out = root / "build" / "config_template_embed.h"
    out.parent.mkdir(exist_ok=True)
    if not out.exists() or out.read_text(encoding="ascii") != text:
        out.write_text(text, encoding="ascii", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
